// Команда консультанта может меняться со временем.
//
//   team        — текущая команда: она идёт в чипы, рейтинги и списки состава;
//   teamHistory — необязательная история переходов, отсортированная по `until`:
//                 [{ until: "2026-07", team: "MS2" }]
//                 читается как «по июл'26 включительно человек был в MS2,
//                 с авг'26 — в той, что указана в `team`».
//
// Статистика по командам считается по месяцам: встречи мая уходят той команде,
// в которой человек был в мае, а не той, где он сейчас. Поэтому перешедший
// консультант появляется в обеих командах — каждая со своим отрезком месяцев,
// и сумма по командам по-прежнему равна общему итогу.
export function teamOf(d, month) {
  const h = d.teamHistory;
  if (!h) return d.team;
  for (const seg of h) if (month <= seg.until) return seg.team;
  return d.team;
}

// Был ли человек в команде хотя бы в одном из месяцев
export function wasInTeam(d, team, months) {
  return months.some((m) => teamOf(d, m) === team);
}
